import swaggerJSDoc from "swagger-jsdoc";
import swaggerUi from "swagger-ui-express";

const options = {
  definition: {
    openapi: "3.0.0",
    info: {
      title: "Caro Game RESTful API Documentation",
      version: "1.0.0",
      description: "Interactive API documentation auto-generated by Swagger UI for Caro Game",
    },
    servers: [
      {
        url: "http://localhost:3000/api",
        description: "Development Local Server",
      },
    ],
    components: {
      securitySchemes: {
        bearerAuth: {
          type: "http",
          scheme: "bearer",
          bearerFormat: "JWT",
          description: "Enter your JWT token in the format: Bearer <token>",
        },
      },
    },
  },
  apis: ["./route/*.js"],
};

const swaggerSpec = swaggerJSDoc(options);

export const setupSwagger = (app) => {
  app.use("/api-docs", swaggerUi.serve, swaggerUi.setup(swaggerSpec));
  console.log("Swagger UI documentation is ready at: http://localhost:3000/api-docs");
};